#!/usr/bin/env node
/**
 * Keeps index.html's <link rel="modulepreload"> list in step with the code.
 *
 * The client is a zero-build set of ES modules. Without hints the browser only
 * finds main.js's imports after main.js has downloaded and parsed, then their
 * imports after THOSE have parsed, and so on: one round trip per level of the
 * import graph before the app can even ask the server who is signed in. The
 * preload list names the whole static graph up front, so it downloads in one
 * parallel wave.
 *
 * Only STATIC imports are listed (they are always needed at start-up); lazy
 * import() targets stay lazy. The server rewrites these hrefs to its
 * build-pinned /b/<build>/js/ URLs (server/utils/clientBuild.js) so they hit
 * the same module-map entries the import map resolves to.
 *
 * It also writes docs/js/utils/preloadGraph.js: the static graphs of what a
 * signed-in start loads next (Home, the players, the v3 extras), minus what
 * index.html already lists. main.js preloads those in one wave while the
 * sign-in checks are on the wire, instead of discovering them level by level.
 *
 *   node scripts/build-preload.js           rewrite docs/index.html + preloadGraph.js
 *   node scripts/build-preload.js --check   exit 1 if either is stale
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const DOCS = path.join(__dirname, '..', 'docs');
const ENTRY = path.join(DOCS, 'js', 'main.js');
const INDEX = path.join(DOCS, 'index.html');
const GRAPH_FILE = path.join(DOCS, 'js', 'utils', 'preloadGraph.js');
// What a signed-in start imports after main.js (main.js: warmSignedInStart,
// loadAppModules). Keep in step with those.
const WARM = {
  HOME_MODULES: ['views/home.js'],
  APP_MODULES: [
    'components/audioPlayer.js', 'components/videoPlayer.js', 'components/miniPlayer.js',
    'components/shortcutsPanel.js', 'app-extras.js',
  ],
};
const START = '<!-- modulepreload:start -->';
const END = '<!-- modulepreload:end -->';

// Static `import … from './x.js'`, `import './x.js'` and `export … from './x.js'`
// (not import()). Comments are stripped first so a commented-out import
// doesn't count.
const STATIC_RE = /(?:^|[;\s])(?:import|export)\s*(?:[^'"();]*?\sfrom\s*)?['"](\.{1,2}\/[^'"]+)['"]/g;

function stripComments(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
}

/** Static import closure of `entry`, in first-seen (breadth-first) order, entry excluded. */
function staticGraph(entry = ENTRY) {
  const seen = new Set([entry]);
  const order = [];
  const queue = [entry];
  while (queue.length) {
    const file = queue.shift();
    const src = stripComments(fs.readFileSync(file, 'utf8'));
    for (const m of src.matchAll(STATIC_RE)) {
      const target = path.resolve(path.dirname(file), m[1]);
      if (seen.has(target)) continue;
      if (!fs.existsSync(target)) throw new Error(`${path.relative(DOCS, file)} imports a missing file: ${m[1]}`);
      seen.add(target);
      order.push(target);
      queue.push(target);
    }
  }
  return order;
}

/** docs/js/utils/preloadGraph.js — warm lists relative to docs/js/, each graph once. */
function graphModule() {
  const JS = path.join(DOCS, 'js');
  const have = new Set([ENTRY, ...staticGraph()]);
  const lines = [
    '// GENERATED by scripts/build-preload.js — do not edit by hand.',
    '// Static module graphs a signed-in start loads after main.js (Home, then the',
    "// players and extras), minus what index.html's modulepreload list already has.",
    '// main.js preloads them in one wave; paths are relative to docs/js/.',
  ];
  for (const [name, entries] of Object.entries(WARM)) {
    const list = [];
    for (const entry of entries) {
      const file = path.join(JS, entry);
      for (const dep of [file, ...staticGraph(file)]) {
        if (have.has(dep)) continue;
        have.add(dep);
        list.push('./' + path.relative(JS, dep).split(path.sep).join('/'));
      }
    }
    lines.push(`export const ${name} = [`, ...list.map(p => `  '${p}',`), '];');
  }
  return lines.join('\n') + '\n';
}

function preloadBlock(indent = '  ') {
  const links = staticGraph().map(file => {
    const href = './' + path.relative(DOCS, file).split(path.sep).join('/');
    return `${indent}<link rel="modulepreload" href="${href}">`;
  });
  return `${START}\n${links.join('\n')}\n${indent}${END}`;
}

function render(html) {
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error(`index.html has no ${START} … ${END} block`);
  const lineStart = html.lastIndexOf('\n', a) + 1;
  const indent = html.slice(lineStart, a);
  return html.slice(0, a) + preloadBlock(indent) + html.slice(b + END.length);
}

if (require.main === module) {
  // preloadGraph.js first: it is itself part of main.js's static graph.
  const graphNow = fs.existsSync(GRAPH_FILE) ? fs.readFileSync(GRAPH_FILE, 'utf8') : '';
  const check = process.argv.includes('--check');
  if (!check && !graphNow) fs.writeFileSync(GRAPH_FILE, 'export const HOME_MODULES = [];\nexport const APP_MODULES = [];\n');
  const graphNext = graphModule();
  const html = fs.readFileSync(INDEX, 'utf8');
  const next = render(html);
  if (check) {
    const stale = [next !== html && 'docs/index.html', graphNext !== graphNow && 'docs/js/utils/preloadGraph.js'].filter(Boolean);
    if (stale.length) {
      console.error(`[build-preload] stale: ${stale.join(', ')} — run: node scripts/build-preload.js`);
      process.exit(1);
    }
    console.log('[build-preload] modulepreload lists are up to date');
  } else {
    if (graphNext !== graphNow) fs.writeFileSync(GRAPH_FILE, graphNext);
    if (next !== html) fs.writeFileSync(INDEX, next);
    console.log(`[build-preload] ${staticGraph().length} modulepreload links in index.html; preloadGraph.js ${graphNext === graphNow ? 'unchanged' : 'written'}`);
  }
}

module.exports = { staticGraph, graphModule, render, START, END, GRAPH_FILE };
